function normalizeForNexusLookup(raw: string): string {
  const folded = raw
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/['’‘`]/g, '')
    .replace(/\([^)]*\)/g, ' ')
    .replace(/\[[^\]]*\]/g, ' ')
    .replace(/[:\-–—/\\.,!?™®©]/g, ' ')

  const noise = new Set([
    'edition',
    'deluxe',
    'ultimate',
    'complete',
    'definitive',
    'goty',
    'directors',
    'director',
    'cut',
    'remastered',
    'remaster',
    'anniversary',
    'enhanced',
    'gold',
    'premium',
    'standard',
    'digital',
    'repack',
    'fitgirl',
    'dodi',
  ])

  const tokens = folded.split(/\s+/).filter(Boolean)
  const kept = tokens.filter((t, i) => i === 0 || !noise.has(t))
  return kept
    .join(' ')
    .replace(/\s+game of the year$/, '')
    .replace(/\s+pc$/, '')
    .trim()
}

export interface NexusModsTarget {
  url: string
  displayPath: string
  isDirectGamePage: boolean
  cleanTitle: string
}

export function resolveNexusModsTarget(gameName: string): NexusModsTarget {
  const norm = normalizeForNexusLookup(gameName)
  const directSlug = NEXUSMODS_SLUG_MAP[norm]
  if (directSlug) {
    return {
      url: `https://www.nexusmods.com/${directSlug}`,
      displayPath: `nexusmods.com/${directSlug}`,
      isDirectGamePage: true,
      cleanTitle: gameName.trim(),
    }
  }

  const cleanSearch = gameName
    .replace(/\b(?:Deluxe|Ultimate|Complete|Definitive|GOTY|Director's Cut|Edition|Repack|FitGirl|DODI)\b/gi, '')
    .replace(/[:™®©]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim() || gameName.trim()

  return {
    url: `https://www.nexusmods.com/games?search=${encodeURIComponent(cleanSearch)}`,
    displayPath: `nexusmods.com/games?search=${cleanSearch}`,
    isDirectGamePage: false,
    cleanTitle: cleanSearch,
  }
}
