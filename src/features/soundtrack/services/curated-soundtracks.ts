export function lookupCuratedSoundtrack(
  game: GameIdentity,
): SoundtrackAlbumWithTracks | null {
  if (!game?.title) return null
  const rawCore = extractCoreGameTitle(game.title).toLowerCase()
  const core = CLASSIC_QUERY_ALIASES[rawCore] || rawCore
  const spec = CURATED_OST_CATALOG[core]
  if (!spec) return null

  if (game.releaseYear && spec.releaseYear) {
    const gmYear = Number.parseInt(String(game.releaseYear).slice(0, 4), 10)
    const spYear = Number.parseInt(String(spec.releaseYear).slice(0, 4), 10)
    if (!Number.isNaN(gmYear) && !Number.isNaN(spYear)) {
      if (gmYear >= 2024 && Math.abs(gmYear - spYear) > 2) {
        return null
      }
    }
  }

  const slug = core.replace(/\s+/g, '_')
  const albumId = `curated_ost_${slug}`
  let totalDurationMs = 0

  const tracks: SoundtrackTrack[] = spec.tracks.map((t, idx) => {
    const durationMs = t.durationSec * 1000
    totalDurationMs += durationMs
    return {
      id: `cur_trk_${slug}_${idx + 1}`,
      album_id: albumId,
      disc_number: 1,
      track_number: idx + 1,
      title: t.title,
      artist: t.artist || spec.artist,
      duration_ms: durationMs,
      preview_url: null,
      stream_url: null,
      download_url: null,
      local_path: null,
      provider_id: 'curated',
      external_id: null,
    }
  })

  return {
    album: {
      id: albumId,
      game_id: game.gameId,
      title: spec.albumTitle,
      album_type: 'original_soundtrack',
      artist: spec.artist,
      release_date: spec.releaseYear || game.releaseYear || null,
      cover_url: game.coverUrl || CURATED_OST_COVERS[core] || resolveAlbumCoverFallback(spec.albumTitle) || null,
      track_count: tracks.length,
      total_duration_ms: totalDurationMs,
      provider_id: 'curated',
      external_id: null,
    },
    tracks,
  }
}

